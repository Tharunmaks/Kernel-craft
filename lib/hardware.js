// Virtual hardware for an OS: CPU, RAM, graphics card. Chosen in the
// Studio's Hardware panel, saved with the project, and applied to the QEMU
// verification VM, the in-browser v86 emulator and (for SDK targets) the
// kernel itself through a generated kc_config.c.

const RESOLUTIONS = ["640x480", "800x600", "1024x768", "1280x720", "1280x1024", "1600x900", "1920x1080"];
const RAM_MB = [32, 64, 128, 256, 512, 1024, 2048];
const VRAM_MB = [8, 16, 32, 64];
const CPU_CORES = [1, 2, 4, 8];
const CPU_MODELS = {
  basic: { label: "Basic (QEMU virtual CPU)", qemu: { "qemu-system-i386": "qemu32", "qemu-system-x86_64": "qemu64" } },
  modern: { label: "Modern (all emulated features)", qemu: { "qemu-system-i386": "max", "qemu-system-x86_64": "max" } },
};
// VESA modes the Linux kernel's vga= option understands (24-bit colour).
const LINUX_VGA_MODES = { "640x480": 0x312, "800x600": 0x315, "1024x768": 0x318, "1280x1024": 0x31b };

const DEFAULTS = { resolution: "800x600", ramMB: 64, vramMB: 16, cpus: 1, cpuModel: "basic" };
const LINUX_DEFAULTS = { ...DEFAULTS, resolution: "1024x768", ramMB: 512, cpus: 2 };

function defaultsFor(tier) {
  return tier.builder === "linux" ? LINUX_DEFAULTS : DEFAULTS;
}

function pick(value, allowed, fallback) {
  const v = typeof fallback === "number" ? Number(value) : value;
  return allowed.includes(v) ? v : fallback;
}

// Cleans user input into a supported configuration and returns notes about
// anything that had to change.
function normalize(input, tier) {
  const d = defaultsFor(tier);
  const src = input && typeof input === "object" ? input : {};
  const hw = {
    resolution: pick(src.resolution, RESOLUTIONS, d.resolution),
    ramMB: pick(src.ramMB, RAM_MB, d.ramMB),
    vramMB: pick(src.vramMB, VRAM_MB, d.vramMB),
    cpus: pick(src.cpus, CPU_CORES, d.cpus),
    cpuModel: CPU_MODELS[src.cpuModel] ? src.cpuModel : d.cpuModel,
  };
  const notes = [];
  const [w, h] = hw.resolution.split("x").map(Number);
  // 32bpp framebuffer has to fit in graphics memory.
  const needVram = VRAM_MB.find((m) => m * 1024 * 1024 >= w * h * 4);
  if (hw.vramMB < needVram) { notes.push(`Graphics memory raised to ${needVram} MB for ${hw.resolution}`); hw.vramMB = needVram; }
  // The SDK keeps a back buffer + wallpaper cache (2 screens) on the heap.
  const needRam = tier.builder === "linux" ? 256 : RAM_MB.find((m) => m >= 16 + Math.ceil((w * h * 4 * 3) / (1024 * 1024)));
  if (hw.ramMB < needRam) { notes.push(`RAM raised to ${needRam} MB`); hw.ramMB = needRam; }
  if (tier.builder === "linux" && !LINUX_VGA_MODES[hw.resolution]) {
    const fallback = w >= 1280 ? "1280x1024" : w >= 1024 ? "1024x768" : "800x600";
    notes.push(`Linux console uses ${fallback} (VESA modes only)`);
    hw.resolution = fallback;
  }
  return { hw, notes };
}

function size(hw) {
  const [width, height] = hw.resolution.split("x").map(Number);
  return { width, height };
}

function qemuArgs(hw, tier) {
  return [
    "-m", String(hw.ramMB),
    "-smp", String(hw.cpus),
    "-cpu", CPU_MODELS[hw.cpuModel].qemu[tier.qemu] || "max",
    "-vga", "none",
    "-device", `VGA,vgamem_mb=${hw.vramMB}`,
  ];
}

function linuxVgaMode(hw) {
  return LINUX_VGA_MODES[hw.resolution] || LINUX_VGA_MODES["1024x768"];
}

// Engine-owned C file for SDK targets (any generated kc_config.c is replaced).
// Self-contained (same layout as kc_hw_config in kc.h) so it still compiles
// if an AI rewrite of kc.h drops the type.
function configSource(hw) {
  const { width, height } = size(hw);
  return `/* Generated by the KernelCraft build engine from the Hardware panel. Do not edit. */
struct kc_hw_config_layout { int width, height, ram_mb, vram_mb, cpus; const char *cpu_model; };
const struct kc_hw_config_layout kc_hw = { ${width}, ${height}, ${hw.ramMB}, ${hw.vramMB}, ${hw.cpus}, "${hw.cpuModel}" };
`;
}

function linuxCmdline(hw) {
  return `console=ttyS0 console=tty0 rdinit=/init quiet loglevel=4 vga=0x${linuxVgaMode(hw).toString(16)}`;
}

function describe(hw) {
  return `${hw.cpus} CPU core${hw.cpus > 1 ? "s" : ""} (${hw.cpuModel}), ${hw.ramMB} MB RAM, ${hw.vramMB} MB graphics memory, ${hw.resolution}`;
}

function options() {
  return {
    resolutions: RESOLUTIONS,
    ramMB: RAM_MB,
    vramMB: VRAM_MB,
    cpus: CPU_CORES,
    cpuModels: Object.fromEntries(Object.entries(CPU_MODELS).map(([id, m]) => [id, m.label])),
    defaults: DEFAULTS,
    linuxDefaults: LINUX_DEFAULTS,
    linuxResolutions: Object.keys(LINUX_VGA_MODES),
  };
}

module.exports = { normalize, qemuArgs, linuxVgaMode, linuxCmdline, configSource, describe, options, size, defaultsFor };
