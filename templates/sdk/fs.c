/* KernelCraft SDK: in-memory hierarchical filesystem (RAM disk). */
#include "kc.h"

static kc_node *root;

static kc_node *node_new(const char *name, bool is_dir, kc_node *parent)
{
    kc_node *n = kcalloc(1, sizeof *n);
    strncpy(n->name, name, sizeof n->name - 1);
    n->is_dir = is_dir;
    n->parent = parent;
    if (parent) {
        /* keep children sorted: directories first, then by name */
        kc_node **pp = &parent->child;
        while (*pp && ((*pp)->is_dir > is_dir || ((*pp)->is_dir == is_dir && strcmp((*pp)->name, name) < 0))) pp = &(*pp)->next;
        n->next = *pp;
        *pp = n;
    }
    return n;
}

static kc_node *child_named(kc_node *dir, const char *name, size_t len)
{
    for (kc_node *c = dir->child; c; c = c->next)
        if (strlen(c->name) == len && !strncmp(c->name, name, len)) return c;
    return NULL;
}

/* Walk path; if create_dirs, make missing directories. Returns the parent
 * directory and the last path component in *leaf (not created). */
static kc_node *walk(const char *path, bool create_dirs, const char **leaf, size_t *leaf_len)
{
    kc_node *cur = root;
    const char *p = path;
    while (*p == '/') p++;
    for (;;) {
        const char *slash = strchr(p, '/');
        size_t len = slash ? (size_t)(slash - p) : strlen(p);
        if (!slash) {
            *leaf = p;
            *leaf_len = len;
            return cur;
        }
        if (len) {
            kc_node *next = child_named(cur, p, len);
            if (!next) {
                if (!create_dirs) return NULL;
                char name[48] = { 0 };
                memcpy(name, p, KC_MIN(len, sizeof name - 1));
                next = node_new(name, true, cur);
            }
            if (!next->is_dir) return NULL;
            cur = next;
        }
        p = slash + 1;
    }
}

kc_node *fs_root(void) { return root; }

kc_node *fs_lookup(const char *path)
{
    const char *leaf;
    size_t len;
    kc_node *dir = walk(path, false, &leaf, &len);
    if (!dir) return NULL;
    if (!len) return dir;
    return child_named(dir, leaf, len);
}

kc_node *fs_mkdir(const char *path)
{
    const char *leaf;
    size_t len;
    kc_node *dir = walk(path, true, &leaf, &len);
    if (!dir) return NULL;
    if (!len) return dir;
    kc_node *n = child_named(dir, leaf, len);
    if (n) return n->is_dir ? n : NULL;
    char name[48] = { 0 };
    memcpy(name, leaf, KC_MIN(len, sizeof name - 1));
    return node_new(name, true, dir);
}

static kc_node *file_for_write(const char *path)
{
    const char *leaf;
    size_t len;
    kc_node *dir = walk(path, true, &leaf, &len);
    if (!dir || !len) return NULL;
    kc_node *n = child_named(dir, leaf, len);
    if (n) return n->is_dir ? NULL : n;
    char name[48] = { 0 };
    memcpy(name, leaf, KC_MIN(len, sizeof name - 1));
    return node_new(name, false, dir);
}

kc_node *fs_append(const char *path, const char *data, size_t n)
{
    kc_node *f = file_for_write(path);
    if (!f) return NULL;
    if (f->size + n + 1 > f->cap) {
        f->cap = (f->size + n + 1) * 2;
        f->data = krealloc(f->data, f->cap);
    }
    memcpy(f->data + f->size, data, n);
    f->size += n;
    f->data[f->size] = 0;
    return f;
}

kc_node *fs_write(const char *path, const char *data, size_t n)
{
    kc_node *f = file_for_write(path);
    if (!f) return NULL;
    f->size = 0;
    return fs_append(path, data, n);
}

static void free_tree(kc_node *n)
{
    for (kc_node *c = n->child, *next; c; c = next) {
        next = c->next;
        free_tree(c);
    }
    kfree(n->data);
    kfree(n);
}

bool fs_remove(const char *path)
{
    kc_node *n = fs_lookup(path);
    if (!n || n == root) return false;
    kc_node **pp = &n->parent->child;
    while (*pp != n) pp = &(*pp)->next;
    *pp = n->next;
    free_tree(n);
    return true;
}

void fs_path(kc_node *n, char *out, size_t cap)
{
    if (n == root) { strncpy(out, "/", cap); return; }
    char tmp[256] = { 0 };
    out[0] = 0;
    for (; n && n != root; n = n->parent) {
        kc_snprintf(tmp, sizeof tmp, "/%s%s", n->name, out);
        strncpy(out, tmp, cap - 1);
        out[cap - 1] = 0;
    }
}

int fs_count(kc_node *dir)
{
    int n = 0;
    for (kc_node *c = dir->child; c; c = c->next) n++;
    return n;
}

static void seed(const char *path, const char *text) { fs_write(path, text, strlen(text)); }

void fs_init(void)
{
    root = node_new("", true, NULL);
    fs_mkdir("/bin");
    fs_mkdir("/home/user/Documents");
    fs_mkdir("/home/user/Pictures");
    fs_mkdir("/tmp");
    seed("/home/user/readme.txt",
         "Welcome to your KernelCraft OS!\n\n"
         "This system was generated by AI and runs on the KernelCraft SDK:\n"
         "interrupts, a PS/2 mouse and keyboard, a 32-bit framebuffer,\n"
         "a heap, this RAM filesystem and a window manager.\n\n"
         "Try the Terminal: type 'help'.\n");
    seed("/home/user/Documents/todo.txt", "- build an OS\n- boot it in the browser\n- ship it\n");
    seed("/etc/motd", "Have fun hacking on your own operating system.\n");
    kc_log("fs: RAM filesystem ready");
}
